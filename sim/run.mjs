// A measured workload against the real isolated regtest stack. No fake mint or in-memory ledger.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { performance } from 'node:perf_hooks';
import { Wallet, getEncodedToken, MintQuoteState } from '../wallet/node_modules/@cashu/cashu-ts/lib/cashu-ts.es.js';
const origin = process.env.COUPURE_URL || 'http://localhost:8080';
const count = Number(process.env.SIM_PAYMENTS || 20);
if (!Number.isSafeInteger(count) || count < 2 || count > 500) throw new Error('SIM_PAYMENTS must be between 2 and 500');
const env = await readFile(new URL('../.env', import.meta.url), 'utf8');
const pin = process.env.OPERATOR_PIN || env.match(/^OPERATOR_PIN=(.+)$/m)?.[1].trim();
const sleep = ms => new Promise(r => setTimeout(r, ms));
const request = async (path, body, headers={}) => {
 const r = await fetch(origin+path,{method:body?'POST':'GET',headers:{'content-type':'application/json',...headers},body:body?JSON.stringify(body):undefined,signal:AbortSignal.timeout(60_000)});
 if(!r.ok) throw new Error(`${path}: HTTP ${r.status}`);return r.json();
};
const login = await request('/api/operator/login',{pin});const headers={Authorization:`Bearer ${login.token}`};
const cable = action => request('/api/demo/island',{action},headers);
async function waitState(state) {
 for(let i=0;i<90;i++){if((await request('/api/health')).island===state)return;await sleep(1000);}throw new Error('island state timeout');
}
const wallet = async()=>{const w=new Wallet(origin+'/mint',{unit:'sat'});await w.loadMint();return {w,proofs:[]};};
const wallets=await Promise.all([wallet(),wallet(),wallet()]);
const sum=ps=>ps.reduce((n,p)=>n+BigInt(p.amount),0n);
const latencies=[];let attempted=0,accepted=0,payments=0,invariantChecks=0;
await cable('restore');await waitState('ONLINE');
let baseline;
for(let i=0;i<15;i++){
 const board=await request('/api/tableau');if(board.liabilities.available){baseline=BigInt(board.liabilities.outstanding_sat);break;}await sleep(1000);
}
if(baseline===undefined)throw new Error('read-only liabilities snapshot unavailable');
const funding=100000n;
const quote=await wallets[0].w.createMintQuoteBolt11(funding);
await request('/api/demo/fund',{bolt11:quote.request});
for(let i=0;i<60;i++){
 if((await wallets[0].w.checkMintQuoteBolt11(quote.quote)).state===MintQuoteState.PAID)break;await sleep(1000);
}
wallets[0].proofs=await wallets[0].w.mintProofsBolt11(funding,quote.quote);
async function invariant(){
 const held=wallets.reduce((n,w)=>n+sum(w.proofs),0n);
 for(let i=0;i<20;i++){
  const b=await request('/api/tableau');
  if(b.liabilities.available&&BigInt(b.liabilities.outstanding_sat)-baseline===held){invariantChecks++;return;}
  await sleep(500);
 }
 throw new Error('liabilities invariant failed; use an isolated demo without other clients');
}
async function payment(index){
 // Respect the mint's per-IP transaction rate limit: all virtual wallets share one host IP.
 await sleep(2200);
 const sender=wallets[0],receiver=wallets[1+(index%2)];const start=performance.now();
 const {keep,send}=await sender.w.send(10n+BigInt(index%8),sender.proofs,{includeFees:true});
 const token=getEncodedToken({mint:origin+'/mint',unit:'sat',proofs:send});
 sender.proofs=keep;receiver.proofs.push(...await receiver.w.receive(token,{requireDleq:true}));
 latencies.push(performance.now()-start);payments++;
 if(index%5===0){
  attempted++;await sleep(2200);
  try{const target=wallets[receiver===wallets[1]?2:1];target.proofs.push(...await target.w.receive(target.w.decodeToken(token),{requireDleq:true}));accepted++;}
  catch(e){if(!/already spent/i.test(String(e)))throw e;}
 }
 await invariant();
}
try{
 for(let i=0;i<count;i++){
  if(i===Math.floor(count/3)){await cable('cut');await waitState('ISLAND');}
  if(i===Math.floor(count*2/3)){await cable('restore');await waitState('ONLINE');}
  await payment(i);
 }
 await invariant();
 if(accepted!==0)throw new Error('a T1 replay was accepted');
 const sorted=[...latencies].sort((a,b)=>a-b), pct=p=>Math.round(sorted[Math.ceil(sorted.length*p)-1]);
 const report={network:'regtest',measured_at:new Date().toISOString(),platform:process.platform,arch:process.arch,payments,double_spends_attempted:attempted,double_spends_accepted:accepted,invariant_checks:invariantChecks,invariant_violations:0,t1_latency_ms:{p50:pct(.5),p95:pct(.95)}};
 await mkdir(new URL('../docs/',import.meta.url),{recursive:true});
 await writeFile(new URL('../docs/metrics.json',import.meta.url),JSON.stringify(report,null,2)+'\n');
 await writeFile(new URL('../docs/METRICS.md',import.meta.url),`# Measured regtest workload\n\nGenerated by make sim at ${report.measured_at}. Isolated real mint, real Lightning funding and a real WAN partition. Host: ${report.platform}/${report.arch}; no Pi hardware claim.\n\n| Measure | Observed |\n|---|---:|\n| Confirmed T1 payments | ${payments} |\n| Replay attempts | ${attempted} |\n| T1 replays accepted | ${accepted} |\n| Liabilities checks | ${invariantChecks} |\n| Liabilities violations | 0 |\n| T1 latency p50 | ${pct(.5)} ms |\n| T1 latency p95 | ${pct(.95)} ms |\n\nLatency includes send and receive, excludes deliberate rate-limit pacing and snapshot waits. No throughput or Pi benchmark is inferred. T2 and queue recovery are covered separately by the engine tests and browser demo.\n`);
 console.log(JSON.stringify(report));
}finally{await cable('restore');}
